"""Status icons (Wi-Fi 16 px, data plane 18 px) from the design boards -> src/status_data.h (1 bit/pixel, rows MSB first)."""
import sys, numpy as np
sys.path.insert(0, "/tmp/claude-0/-home-claude/87ee4205-97d5-5eb5-9b0e-5c095f8ffc16/scratchpad/eink")
from icons import STATES
names = ["wifi_ok", "wifi_search", "wifi_down", "data_live", "data_stale", "data_none"]
with open("../src/status_data.h", "w") as o:
    o.write("// generated by tools/bake_status.py\n#pragma once\n#include <stdint.h>\nstruct Bmp1 { uint8_t w, h; const uint8_t* bits; };\n")
    for n in names:
        a = np.asarray(STATES[n]).astype(bool); b = np.packbits(a, axis=1)
        o.write(f"static const uint8_t ST_{n}[] PROGMEM = {{" + ",".join(str(int(v)) for v in b.ravel()) + "};\n")
    o.write("static const Bmp1 ST[] PROGMEM = {" + ",".join("{%d,%d,ST_%s}" % (np.asarray(STATES[n]).shape[1], np.asarray(STATES[n]).shape[0], n) for n in names) + "};\n")
    o.write("enum { ST_WIFI_OK, ST_WIFI_SEARCH, ST_WIFI_DOWN, ST_DATA_LIVE, ST_DATA_STALE, ST_DATA_NONE };\n")
print("ok")
