"""Bake the ADS-B Radar top-down icons (credit: https://adsb-radar.com) into firmware sprites.
Each (icon, size class) pair becomes a 2x-supersampled 1-bit mask, nose up; the firmware rotates it at draw time.
Writes src/icons_data.h"""
import sys, io, math, numpy as np
sys.path.insert(0, "/tmp/claude-0/-home-claude/87ee4205-97d5-5eb5-9b0e-5c095f8ffc16/scratchpad/eink")
import mapicons as mi, silh
from PIL import Image
from playwright.sync_api import sync_playwright

codes = set(mi.TYPE_ICON) | {c for s in silh.CODES.values() for c in s}
cats = ["A0", "A1", "A2", "A3", "A4", "A5", "A6", "A7", "B1", "B2", "B4", "B6"]
need = {}                                                    # (file, klass) -> sprite index
def want(f, k):
    if (f, k) not in need: need[(f, k)] = len(need)
    return need[(f, k)]
type_tab = {c: want(mi.pick(c, silh.klass(c, None), None), silh.klass(c, None)) for c in sorted(codes)}
cat_tab = {}
for c in cats:
    k = silh.klass("ZZZZ", c); cat_tab[c] = want(mi.pick("ZZZZ", k, c), k)
default = want(mi.pick("ZZZZ", silh.klass("ZZZZ", None), None), silh.klass("ZZZZ", None))

sprites = [None] * len(need)
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page()
    for (f, k), idx in need.items():
        x0, y0, x1, y1 = mi.BB[f]; s = mi.scale(f, k)
        hd = math.hypot(x1 - x0, y1 - y0) / 2 * s; side = 2 * math.ceil(hd) + 2; n2 = side * 2
        cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
        svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{n2}" height="{n2}" viewBox="0 0 {n2} {n2}" shape-rendering="geometricPrecision">'
               f'<g transform="translate({n2/2},{n2/2}) scale({2*s}) translate({-cx},{-cy})" fill="#000">{mi.body(f)}</g></svg>')
        pg.set_viewport_size({"width": n2, "height": n2}); pg.set_content(f'<body style="margin:0;background:#fff">{svg}</body>')
        a = np.asarray(Image.open(io.BytesIO(pg.screenshot())).convert("L")) < 128
        sprites[idx] = (side, n2, np.packbits(a, axis=1))
    b.close()
names = {v: k for k, v in need.items()}
with open("../src/icons_data.h", "w") as o:
    o.write("// generated by tools/bake_icons.py from the ADS-B Radar free icon pack (https://adsb-radar.com)\n#pragma once\n#include <stdint.h>\n")
    for i, (side, n2, bits) in enumerate(sprites):
        o.write(f"static const uint8_t SPR{i}[] PROGMEM = {{" + ",".join(str(int(v)) for v in bits.ravel()) + f"}}; // {names[i][0]} {names[i][1]}\n")
    o.write("struct Sprite { uint8_t side; uint8_t n2; const uint8_t* bits; };\n")
    o.write("static const Sprite SPRITES[] PROGMEM = {" + ",".join("{%d,%d,SPR%d}" % (s, n, i) for i, (s, n, _) in enumerate(sprites)) + "};\n")
    o.write("struct TypeSpr { char code[5]; uint8_t spr; };\nstatic const TypeSpr TYPE_TAB[] PROGMEM = {" + ",".join('{"%s",%d}' % (c, v) for c, v in type_tab.items()) + "};\n")
    o.write(f"static const uint16_t TYPE_N = {len(type_tab)};\n")
    o.write("struct CatSpr { char cat[3]; uint8_t spr; };\nstatic const CatSpr CAT_TAB[] PROGMEM = {" + ",".join('{"%s",%d}' % (c, v) for c, v in cat_tab.items()) + "};\n")
    o.write(f"static const uint8_t CAT_N = {len(cat_tab)}, DEFAULT_SPR = {default};\n")
total = sum(b.size for _, _, b in sprites)
print(len(sprites), "sprites,", len(type_tab), "type codes,", total, "bytes of bitmap data")
