"""Bake a pixel font to an Adafruit_GFX font header. Usage: gfxfont.py <font.ttf|woff2> <px> <name> <out.h>
Chars 0x20-0x7E as-is; '→' -> 0x80, '–' -> 0x81, '·' -> 0x82 (draw code maps UTF-8 to these)."""
import sys, io
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont
src, px, name, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
if src.endswith(".woff2"):
    f = TTFont(src); f.flavor = None; buf = io.BytesIO(); f.save(buf); buf.seek(0); font = ImageFont.truetype(buf, px, layout_engine=ImageFont.Layout.BASIC)
else:
    font = ImageFont.truetype(src, px, layout_engine=ImageFont.Layout.BASIC)
MAP = {**{c: chr(c) for c in range(0x20, 0x7F)}, 0x80: "→", 0x81: "–", 0x82: "·"}
asc, desc = font.getmetrics(); yadv = asc + desc
bitmap = bytearray(); glyphs = []
for code in range(0x20, 0x83):
    ch = MAP.get(code)
    if ch is None: glyphs.append((len(bitmap), 0, 0, 0, 0, 0)); continue
    im = Image.new("L", (px * 3, px * 3), 0); d = ImageDraw.Draw(im); d.fontmode = "1"
    d.text((px, px), ch, font=font, fill=255, anchor="ls")           # baseline at y=px, origin x=px
    adv = int(round(font.getlength(ch)))
    bb = im.point(lambda v: 255 if v > 127 else 0).getbbox()
    if not bb: glyphs.append((len(bitmap), 0, 0, adv, 0, 0)); continue
    x0, y0, x1, y1 = bb; w, h = x1 - x0, y1 - y0
    off = len(bitmap); bits = 0; n = 0; cur = 0
    for y in range(y0, y1):
        for x in range(x0, x1):
            cur = (cur << 1) | (1 if im.getpixel((x, y)) > 127 else 0); n += 1
            if n == 8: bitmap.append(cur); cur = 0; n = 0
    if n: bitmap.append(cur << (8 - n))
    glyphs.append((off, w, h, adv, x0 - px, y0 - px))               # yOffset relative to baseline (negative = above)
with open(out, "w") as o:
    o.write(f"// {name}: {px}px pixel font, generated by tools/gfxfont.py\n#pragma once\n#include <Adafruit_GFX.h>\n")
    o.write(f"const uint8_t {name}Bitmaps[] PROGMEM = {{" + ",".join(str(b) for b in bitmap) + "};\n")
    o.write(f"const GFXglyph {name}Glyphs[] PROGMEM = {{" + ",".join("{%d,%d,%d,%d,%d,%d}" % g for g in glyphs) + "};\n")
    o.write(f"extern const GFXfont {name} PROGMEM = {{(uint8_t*){name}Bitmaps,(GFXglyph*){name}Glyphs,0x20,0x82,{yadv}}};\n")
print(name, px, "ok", len(bitmap), "bytes, yAdvance", yadv)
