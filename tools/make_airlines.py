#!/usr/bin/env python3
"""ICAO -> IATA airline codes for the flight-number display (AFR98E -> AF98E).
Source: OpenFlights airlines.dat (ODbL), https://github.com/jpatokal/openflights . Usage: make_airlines.py airlines.dat
Writes tools/airlines_iata.csv and src/airline_iata.h (sorted by ICAO, 5 chars each: 3 ICAO + 2 IATA)."""
import csv, os, sys
src = sys.argv[1]; here = os.path.dirname(os.path.abspath(__file__))
best = {}
for r in csv.reader(open(src, encoding="utf-8")):
    if len(r) < 8: continue
    iata, icao, active = r[3].strip(), r[4].strip(), r[7].strip()
    if len(iata) != 2 or len(icao) != 3 or not icao.isalpha() or not iata.isalnum() or iata in ("\\N", "-") or icao == "N/A": continue
    key = icao.upper(); score = 1 if active == "Y" else 0
    if key not in best or score > best[key][1]: best[key] = (iata.upper(), score)
best["BAW"] = ("BA", 1); best["AFR"] = ("AF", 1); best["EZY"] = ("U2", 1); best["EXS"] = ("LS", 1); best["RYR"] = ("FR", 1)   # fix known OpenFlights oddities
rows = sorted((k, v[0]) for k, v in best.items())
with open(os.path.join(here, "airlines_iata.csv"), "w") as f:
    for k, v in rows: f.write(f"{k},{v}\n")
with open(os.path.join(here, "..", "src", "airline_iata.h"), "w") as f:
    f.write("#pragma once\n// Generated by tools/make_airlines.py from OpenFlights (ODbL). Sorted by ICAO; 3 ICAO letters + 2 IATA characters.\n")
    f.write(f"static const int AIRLINE_N = {len(rows)};\nstatic const char AIRLINE_TBL[][6] = {{\n")
    for i in range(0, len(rows), 8): f.write("  " + ",".join(f'"{k}{v}"' for k, v in rows[i:i + 8]) + ",\n")
    f.write("};\n")
print(len(rows), "airlines")
