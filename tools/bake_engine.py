"""Bake the engine picture for the Engines view into src/engine_img.h (1-bit bitmap in flash + anchors).
Usage: python3 tools/bake_engine.py   (needs numpy, scipy, Pillow; renders a 3D turbofan, see tools/engine3d.py)"""
import numpy as np, os, sys
sys.path.insert(0, os.path.dirname(__file__))
import engine3d
ink, an, fill = engine3d.render((440, 300), 108, 24, -10, 2)
ys, xs = np.where(ink); bx0, bx1, by0, by1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
crop = ink[by0:by1, bx0:bx1]; eh, ew = crop.shape
P = lambda k: np.array([an[k][0] - bx0, an[k][1] - by0])
Cf, Cr = P('front'), P('rear'); T = P('face_top') - Cf; Lw = P('face_l') - Cf
th = np.linspace(0, 2 * np.pi, 1440, endpoint=False)
rim = Cf[None, :] + 1.12 * (np.cos(th)[:, None] * T[None, :] + np.sin(th)[:, None] * Lw[None, :])
left = rim[rim[:, 0] < Cf[0] - 2]; left = left[np.argsort(left[:, 1])]
y0, y1 = int(np.ceil(left[0, 1])), int(np.floor(left[-1, 1]))
rimx = [int(round(float(np.interp(y, left[:, 1], left[:, 0])))) for y in range(y0, y1 + 1)]
stride = (ew + 7) // 8; data = bytearray()
for r in range(eh):
    for b in range(stride):
        v = 0
        for k in range(8):
            x = b * 8 + k; v = (v << 1) | (1 if x < ew and crop[r, x] else 0)
        data.append(v)
out = os.path.join(os.path.dirname(__file__), "..", "src", "engine_img.h")
with open(out, "w") as f:
    f.write("// Engine picture for the Engines view, generated by tools/bake_engine.py (3D render, 1 bit per pixel, MSB first)\n#pragma once\n#include <Arduino.h>\n")
    f.write(f"#define ENG_W {ew}\n#define ENG_H {eh}\n")
    f.write(f"static const float ENG_FRONT[2] = {{{Cf[0]:.2f}f,{Cf[1]:.2f}f}};   // centre of the fan face\n")
    f.write(f"static const float ENG_REAR[2] = {{{Cr[0]:.2f}f,{Cr[1]:.2f}f}};    // tip of the tail cone\n")
    f.write(f"#define ENG_RIM_Y0 {y0}\n#define ENG_RIM_N {len(rimx)}\n")
    f.write("static const int16_t ENG_RIMX[ENG_RIM_N] PROGMEM = {" + ",".join(map(str, rimx)) + "};   // x of the fan rim (left arc) for each row\n")
    f.write("static const uint8_t ENG_BITS[] PROGMEM = {" + ",".join(map(str, data)) + "};\n")
print("engine", ew, "x", eh, "bytes", len(data), "rim rows", len(rimx), "front", Cf, "rear", Cr)
